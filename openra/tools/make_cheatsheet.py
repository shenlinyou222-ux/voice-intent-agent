# -*- coding: utf-8 -*-
"""从 profile 生成中文「语音指令表」（给玩家看的一页纸）。

用法: python openra/tools/make_cheatsheet.py [profile_id]
产出: openra/语音指令表.md
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OPENRA_DIR = HERE.parent
sys.path.insert(0, str(OPENRA_DIR.parent))

from openra import game_profile  # noqa: E402

# 每个意图：怎么说 → 游戏里发生什么
DOC = {
    "game_select": ("选中所有坦克 / 选中所有步兵 / 选中所有矿车 / 选中所有建筑 / 全选部队",
                    "把符合条件的单位选中（游戏里真的框上，你能看到）"),
    "game_move": ("移动到 60 40 / 移动到六十 四十 / 部队开到 30 20",
                  "选中的单位走过去（没选中就自动挑能动的）"),
    "game_attack": ("攻击最近的敌人 / 攻击 60 40 / 打掉那个炮台",
                    "打指定坐标，或自动找视野内最近的敌人"),
    "game_attackmove": ("攻击前进到 70 70 / 边打边进",
                        "一路打过去（Attack-Move）"),
    "game_stop": ("停止 / 全部停下 / 别动了", "取消当前动作"),
    "game_scatter": ("散开 / 分散", "单位散开躲炮"),
    "game_guard": ("守卫 40 40 / 守住这里", "原地守卫指定位置"),
    "game_stance": ("姿态防御 / 切换成停火 / 自由开火", "切换开火姿态（停火/还击/防御/主动攻击）"),
    "game_harvest": ("矿车去采矿 / 去挖矿", "所有采矿车去找矿（没矿车就明说 0 辆）"),
    "game_deploy": ("基地车展开 / 部署基地", "智能展开：原地放不下会先挪到能放的地方"),
    "game_build": ("建造坦克 / 造两个矿车 / 电厂 / 特斯拉 / 维修工厂 / 三个火箭兵",
                   "下单生产（数量用「两个/三辆」都认；光说名字也算造）"),
    "game_place": ("放置电厂 / 把电厂放在这里", "把造好的建筑放到地图上（自动找空位）"),
    "game_cancel": ("取消建造坦克 / 不造坦克了 / 停止生产步兵", "取消生产队列里的东西"),
    "game_group": ("三辆坦克二步兵编为一队 / 全部坦克编为一队 / 所有矿车编为二队 / 编为一队",
                   "把指定单位编成 1~9 队（红警控制组）；「编为一队」= 把当前选中的编进去"),
    "game_explore": ("自动探索 / 侦察兵去探索 / 派个单位去探路",
                     "挑跑得最快的（或选中的）单位，沿未探索区域串出的路线探图"),
    "game_repair": ("修理建筑 / 修复我的建筑", "修理选中的建筑"),
    "game_sell": ("卖掉电厂 / 出售这个炮台", "出售选中的建筑（退钱）"),
    "game_capture": ("占领敌方建筑 / 工程师占领", "占领视野内最近的敌方建筑"),
    "game_rally": ("设置集结点 40 40 / 集结点设在这里", "给选中的兵营/工厂设集结点"),
    "game_state": ("现在有多少钱 / 报告战况 / 我还有多少单位", "念一遍现金/电力/单位/敌人数量"),
    "game_ping": ("标记 50 50 / 标记这里", "在小地图上打个雷达标记"),
    "game_chat": ("喊话进攻 / 告诉队友我来了", "往游戏聊天框发一句话"),
}


def main():
    pid = sys.argv[1] if len(sys.argv) > 1 else None
    p = game_profile.load(pid)
    L: list[str] = []
    A = L.append

    A(f"# 红警语音指令表（profile: {p.id}）\n")
    A(f"> 版本戳：热词 `{p.hotwords_version}` ／ 意图 `{p.intent_version}` ／ 索引 `{p.index_version}`\n")
    A("## 一、怎么说\n")
    A("| 意图 | 你可以这样说 | 游戏里会发生什么 |")
    A("|---|---|---|")
    for it in p.intents:
        iid = it["id"]
        say, does = DOC.get(iid, ("—", it.get("desc", "")))
        A(f"| `{iid}` | {say} | {does} |")
    A("")

    A("## 二、能造的东西（说中文名就行）\n")
    A("| 说 | actor | 队列 | 英文名 |")
    A("|---|---|---|---|")
    for item in p.items:
        A(f"| {item['name']}（{ '/'.join(item['aliases'][:3]) } …） | `{item['id']}` | {item['queue']} | {item['en']} |")
    A("")

    A("## 三、使用要点\n")
    A("- **先选中再下令**：说「选中所有坦克」→ 再说「移动到 60 40」。没选中时，桥会按指令能力兜底"
      "（采矿只给矿车、移动只给能动的、卖/修只给建筑），不会乱发给建筑。")
    A("- **⭐ 一句话可以说多个命令**：「电厂、精炼厂」→ 两个都造；"
      "「造两个矿车，再造一个电厂」→ 先矿车后电厂；「选中所有坦克，然后攻击最近的敌人」→ 选中并进攻。"
      "用「、」「，」或「然后/再/接着」隔开即可。")
    A("- **⭐ 流式抢跑**：按住说话的**过程中**就会边转写边执行（流式模型按固定 5 秒窗口解码，"
      "所以短口令基本还是松手即执行；一口气说很长的多命令时，前面几条会边说边做）。"
      "松手后的整段权威结果会**跳过已经执行过的动作**，不会做两遍。")
    A("- **坐标**：直接说数字（「移动到 60 40」）或中文数字（「移动到六十 四十」）都行；"
      "范围 0~128。说不出坐标的动作会明确告诉你「需要坐标」，不会乱动。")
    A("- **数量**：造两个 / 三辆 / 五个 都认。光说名字也算造：「电厂」「特斯拉」「猛犸」。")
    A("- **同音兜底**：ASR 把「精炼厂」听成「金炼厂」也能对上（拼音近似匹配）。")
    A("- **反馈**：每条指令执行后会在游戏聊天框回一行中文 + 打一个雷达标记，你一眼能看到它听懂了什么。")
    A("- **安全**：单位名说错 → 干净报错并给相近候选，不会崩游戏；桥只控制你自己的单位，"
      "只绑 127.0.0.1。")
    A("")

    out = OPENRA_DIR / "语音指令表.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"written: {out}")
    print(f"  profile={p.id}  意图={len(p.intents)}  可造条目={len(p.items)}")


if __name__ == "__main__":
    main()
